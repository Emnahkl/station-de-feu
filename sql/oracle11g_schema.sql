-- FireStation Manager shared schema for Oracle 11g XE.
-- Run while connected as the application schema owner. This script is for a
-- fresh schema; it never drops existing data. IDs use sequences and triggers
-- because Oracle 11g does not support identity columns.

CREATE TABLE ZONE_COUVERTURE (
    ID_ZONE NUMBER PRIMARY KEY,
    NOM VARCHAR2(100) NOT NULL,
    REGION VARCHAR2(100),
    SUPERFICIE NUMBER(12,2),
    POPULATION NUMBER(12),
    NIVEAU_RISQUE VARCHAR2(30),
    TEMPS_INTERVENTION NUMBER(6),
    TEMPS_INTERVENTION_MOYEN NUMBER(6),
    LATITUDE NUMBER(10,7),
    LONGITUDE NUMBER(10,7)
);

CREATE TABLE EMPLOYE (
    ID_EMPLOYE NUMBER(10) PRIMARY KEY,
    NOM VARCHAR2(50) NOT NULL,
    PRENOM VARCHAR2(50) NOT NULL,
    PHOTO VARCHAR2(255),
    GRADE VARCHAR2(50),
    SPECIALITE VARCHAR2(50),
    TELEPHONE VARCHAR2(20),
    EMAIL VARCHAR2(100),
    ROLE VARCHAR2(50),
    STATUT VARCHAR2(30) DEFAULT 'En service',
    EMPLOI_TEMPS VARCHAR2(100) DEFAULT 'Aucune',
    VOLONTAIRE NUMBER(1) DEFAULT 0 CHECK (VOLONTAIRE IN (0,1))
);

CREATE TABLE VEHICULES (
    IMMATRICULATION VARCHAR2(20) PRIMARY KEY,
    TYPE VARCHAR2(50) NOT NULL,
    ETAT VARCHAR2(30),
    MODELE VARCHAR2(50),
    KILOMETRAGE NUMBER(10) DEFAULT 0 CHECK (KILOMETRAGE >= 0),
    DERNIERE_MAINTENANCE DATE,
    KM_DERNIERE_MAINTENANCE NUMBER(10)
);

CREATE TABLE VEHICULE_EVENEMENTS (
    ID_EVENEMENT NUMBER PRIMARY KEY,
    IMMATRICULATION VARCHAR2(20) NOT NULL,
    TYPE_EVENEMENT VARCHAR2(40) NOT NULL,
    DATE_EVENEMENT DATE DEFAULT SYSDATE NOT NULL,
    DETAILS VARCHAR2(500),
    CONSTRAINT FK_VEH_EVT_VEH FOREIGN KEY (IMMATRICULATION)
        REFERENCES VEHICULES(IMMATRICULATION) ON DELETE CASCADE
);

CREATE TABLE EQUIPEMENT (
    ID NUMBER(10) PRIMARY KEY,
    NOM VARCHAR2(100) NOT NULL,
    TYPE_EQUIP VARCHAR2(50),
    QUANTITE NUMBER(6) DEFAULT 0 CHECK (QUANTITE >= 0),
    DATE_ACQUISITION DATE,
    ETAT VARCHAR2(30),
    DATE_CONTROLE DATE,
    DATE_PEREMPTION DATE,
    AFFECTATION VARCHAR2(100),
    IMMATRICULATION VARCHAR2(20),
    SEUIL_ALERTE NUMBER(6) DEFAULT 5,
    CONSTRAINT FK_EQUIP_VEH FOREIGN KEY (IMMATRICULATION)
        REFERENCES VEHICULES(IMMATRICULATION) ON DELETE SET NULL
);

CREATE TABLE CAMPAGNE (
    ID_CAMPAGNE NUMBER(10) PRIMARY KEY,
    TITRE VARCHAR2(100) NOT NULL,
    THEME VARCHAR2(100) NOT NULL,
    DATE_CAMPAGNE DATE,
    LIEU VARCHAR2(100),
    PUBLIC_CIBLE VARCHAR2(100),
    NB_PARTICIPANTS NUMBER(6) DEFAULT 0 CHECK (NB_PARTICIPANTS >= 0),
    ID_ZONE NUMBER(10),
    ID_EMPLOYE NUMBER(10),
    DESCRIPTION VARCHAR2(1000),
    DATE_DEBUT DATE,
    DATE_FIN DATE,
    BUDGET NUMBER(12,2) DEFAULT 0 CHECK (BUDGET >= 0),
    STATUT VARCHAR2(30),
    SCORE_IMPACT NUMBER(5,2) CHECK (SCORE_IMPACT BETWEEN 0 AND 100),
    CONSTRAINT FK_CAMP_ZONE FOREIGN KEY (ID_ZONE) REFERENCES ZONE_COUVERTURE(ID_ZONE),
    CONSTRAINT FK_CAMP_EMP FOREIGN KEY (ID_EMPLOYE) REFERENCES EMPLOYE(ID_EMPLOYE),
    CONSTRAINT CK_CAMP_DATES CHECK (DATE_FIN IS NULL OR DATE_DEBUT IS NULL OR DATE_FIN >= DATE_DEBUT)
);

CREATE TABLE INTERVENTIONS (
    ID_INTERVENTION NUMBER PRIMARY KEY,
    TYPE_INTERVENTION VARCHAR2(50) NOT NULL,
    ADRESSE VARCHAR2(150) NOT NULL,
    DATE_INTERVENTION DATE NOT NULL,
    HEURE VARCHAR2(5) NOT NULL,
    GRAVITE VARCHAR2(20),
    STATUT VARCHAR2(20),
    ID_ZONE NUMBER NOT NULL,
    CONSTRAINT FK_INTER_ZONE FOREIGN KEY (ID_ZONE) REFERENCES ZONE_COUVERTURE(ID_ZONE)
);

CREATE TABLE PARTICIPER_UTILISER (
    ID_EMPLOYE NUMBER(10) NOT NULL,
    IMMATRICULATION VARCHAR2(20) NOT NULL,
    ID_INTERVENTION NUMBER NOT NULL,
    CONSTRAINT PK_PARTICIPER_UTILISER PRIMARY KEY (ID_EMPLOYE, IMMATRICULATION, ID_INTERVENTION),
    CONSTRAINT FK_PART_EMP FOREIGN KEY (ID_EMPLOYE) REFERENCES EMPLOYE(ID_EMPLOYE) ON DELETE CASCADE,
    CONSTRAINT FK_PART_VEH FOREIGN KEY (IMMATRICULATION) REFERENCES VEHICULES(IMMATRICULATION),
    CONSTRAINT FK_PART_INT FOREIGN KEY (ID_INTERVENTION) REFERENCES INTERVENTIONS(ID_INTERVENTION) ON DELETE CASCADE
);

CREATE TABLE NECESSITER (
    ID_EQUIPEMENT NUMBER(10) NOT NULL,
    ID_INTERVENTION NUMBER NOT NULL,
    QTE_UTILISEE NUMBER(6) DEFAULT 0 CHECK (QTE_UTILISEE >= 0),
    CONSTRAINT PK_NECESSITER PRIMARY KEY (ID_EQUIPEMENT, ID_INTERVENTION),
    CONSTRAINT FK_NEC_EQUIP FOREIGN KEY (ID_EQUIPEMENT) REFERENCES EQUIPEMENT(ID),
    CONSTRAINT FK_NEC_INTER FOREIGN KEY (ID_INTERVENTION) REFERENCES INTERVENTIONS(ID_INTERVENTION) ON DELETE CASCADE
);

CREATE TABLE ANIMER (
    ID_EMPLOYE NUMBER(10) NOT NULL,
    ID_CAMPAGNE NUMBER(10) NOT NULL,
    CONSTRAINT PK_ANIMER PRIMARY KEY (ID_EMPLOYE, ID_CAMPAGNE),
    CONSTRAINT FK_ANIM_EMP FOREIGN KEY (ID_EMPLOYE) REFERENCES EMPLOYE(ID_EMPLOYE) ON DELETE CASCADE,
    CONSTRAINT FK_ANIM_CAMP FOREIGN KEY (ID_CAMPAGNE) REFERENCES CAMPAGNE(ID_CAMPAGNE) ON DELETE CASCADE
);

CREATE TABLE PLANNING_JOUR (
    ID_EMPLOYE NUMBER(10) NOT NULL,
    JOUR DATE NOT NULL,
    GARDE VARCHAR2(100),
    CONSTRAINT PK_PLANNING_JOUR PRIMARY KEY (ID_EMPLOYE, JOUR),
    CONSTRAINT FK_PLAN_EMP FOREIGN KEY (ID_EMPLOYE) REFERENCES EMPLOYE(ID_EMPLOYE) ON DELETE CASCADE
);

CREATE SEQUENCE SEQ_ZONE START WITH 1 INCREMENT BY 1 NOCACHE;
CREATE SEQUENCE SEQ_EMPLOYE START WITH 1 INCREMENT BY 1 NOCACHE;
CREATE SEQUENCE SEQ_VEHICULE_EVENEMENT START WITH 1 INCREMENT BY 1 NOCACHE;
CREATE SEQUENCE SEQ_EQUIPEMENT START WITH 1 INCREMENT BY 1 NOCACHE;
CREATE SEQUENCE SEQ_CAMPAGNE START WITH 1 INCREMENT BY 1 NOCACHE;
CREATE SEQUENCE SEQ_INTERVENTIONS START WITH 1 INCREMENT BY 1 NOCACHE;

CREATE OR REPLACE TRIGGER TRG_ZONE_ID BEFORE INSERT ON ZONE_COUVERTURE
FOR EACH ROW WHEN (NEW.ID_ZONE IS NULL)
BEGIN SELECT SEQ_ZONE.NEXTVAL INTO :NEW.ID_ZONE FROM DUAL; END;
/
CREATE OR REPLACE TRIGGER TRG_EMPLOYE_ID BEFORE INSERT ON EMPLOYE
FOR EACH ROW WHEN (NEW.ID_EMPLOYE IS NULL)
BEGIN SELECT SEQ_EMPLOYE.NEXTVAL INTO :NEW.ID_EMPLOYE FROM DUAL; END;
/
CREATE OR REPLACE TRIGGER TRG_VEH_EVT_ID BEFORE INSERT ON VEHICULE_EVENEMENTS
FOR EACH ROW WHEN (NEW.ID_EVENEMENT IS NULL)
BEGIN SELECT SEQ_VEHICULE_EVENEMENT.NEXTVAL INTO :NEW.ID_EVENEMENT FROM DUAL; END;
/
CREATE OR REPLACE TRIGGER TRG_EQUIP_ID BEFORE INSERT ON EQUIPEMENT
FOR EACH ROW WHEN (NEW.ID IS NULL)
BEGIN SELECT SEQ_EQUIPEMENT.NEXTVAL INTO :NEW.ID FROM DUAL; END;
/
CREATE OR REPLACE TRIGGER TRG_CAMPAGNE_ID BEFORE INSERT ON CAMPAGNE
FOR EACH ROW WHEN (NEW.ID_CAMPAGNE IS NULL)
BEGIN SELECT SEQ_CAMPAGNE.NEXTVAL INTO :NEW.ID_CAMPAGNE FROM DUAL; END;
/
CREATE OR REPLACE TRIGGER TRG_CAMPAGNE_DATES BEFORE INSERT OR UPDATE ON CAMPAGNE
FOR EACH ROW
BEGIN
    IF :NEW.DATE_CAMPAGNE IS NULL THEN
        :NEW.DATE_CAMPAGNE := NVL(:NEW.DATE_DEBUT, :NEW.DATE_FIN);
    END IF;
    IF :NEW.DATE_DEBUT IS NULL THEN :NEW.DATE_DEBUT := :NEW.DATE_CAMPAGNE; END IF;
    IF :NEW.DATE_FIN IS NULL THEN :NEW.DATE_FIN := :NEW.DATE_CAMPAGNE; END IF;
END;
/
CREATE OR REPLACE TRIGGER TRG_INTERVENTIONS_ID BEFORE INSERT ON INTERVENTIONS
FOR EACH ROW WHEN (NEW.ID_INTERVENTION IS NULL)
BEGIN SELECT SEQ_INTERVENTIONS.NEXTVAL INTO :NEW.ID_INTERVENTION FROM DUAL; END;
/

-- Read-only compatibility view for zone/campaign analytics written against
-- the earlier singular INTERVENTION table. All writes go to INTERVENTIONS.
CREATE OR REPLACE VIEW INTERVENTION AS
SELECT ID_INTERVENTION, TYPE_INTERVENTION AS TYPE, ADRESSE,
       DATE_INTERVENTION + TO_NUMBER(SUBSTR(HEURE,1,2))/24
           + TO_NUMBER(SUBSTR(HEURE,4,2))/(24*60) AS DATE_HEURE,
       ID_ZONE, GRAVITE
  FROM INTERVENTIONS;

-- Compatibility views used by the advanced intervention assignment module.
CREATE OR REPLACE VIEW EMPLOYES AS
SELECT ID_EMPLOYE, NOM || ' ' || PRENOM AS NOM_PRENOM, GRADE, SPECIALITE
  FROM EMPLOYE;
CREATE OR REPLACE VIEW EQUIPEMENTS AS
SELECT ID AS ID_EQUIPEMENT, TYPE_EQUIP AS CATEGORIE, NOM AS DESIGNATION,
       QUANTITE, ETAT, DATE_PEREMPTION, IMMATRICULATION
  FROM EQUIPEMENT;
CREATE OR REPLACE VIEW PARTICIPER AS
SELECT ID_EMPLOYE, IMMATRICULATION, ID_INTERVENTION FROM PARTICIPER_UTILISER;

CREATE INDEX IX_INTER_ZONE_DATE ON INTERVENTIONS(ID_ZONE, DATE_INTERVENTION);
CREATE INDEX IX_CAMP_ZONE ON CAMPAGNE(ID_ZONE);
CREATE INDEX IX_PART_INTER ON PARTICIPER_UTILISER(ID_INTERVENTION);


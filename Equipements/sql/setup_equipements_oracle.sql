-- SafeStation / module Équipements
-- À exécuter UNE FOIS dans SQL Developer, connecté en SAFESTATION sur XEPDB1.
-- Ce script respecte la table EQUIPEMENTS du MLD (nom au pluriel).
-- Si elle existe, il conserve ses données et ajoute seulement les colonnes
-- nécessaires au formulaire CRUD qui manquent.

SET SERVEROUTPUT ON;

DECLARE
    v_count NUMBER;
    v_identity NUMBER;
    v_id_trigger NUMBER;
    v_next_id NUMBER;

    PROCEDURE ajouter_colonne(p_nom VARCHAR2, p_definition VARCHAR2) IS
        v_present NUMBER;
    BEGIN
        SELECT COUNT(*) INTO v_present
          FROM USER_TAB_COLUMNS
         WHERE TABLE_NAME = 'EQUIPEMENTS'
           AND COLUMN_NAME = UPPER(p_nom);
        IF v_present = 0 THEN
            EXECUTE IMMEDIATE 'ALTER TABLE EQUIPEMENTS ADD (' || p_nom || ' ' || p_definition || ')';
            DBMS_OUTPUT.PUT_LINE('Colonne ajoutée : ' || p_nom);
        ELSE
            DBMS_OUTPUT.PUT_LINE('Colonne déjà présente : ' || p_nom);
        END IF;
    END;
BEGIN
    SELECT COUNT(*) INTO v_count
      FROM USER_TABLES
     WHERE TABLE_NAME = 'EQUIPEMENTS';

    IF v_count = 0 THEN
        EXECUTE IMMEDIATE q'~CREATE TABLE EQUIPEMENTS (
            ID_EQUIPEMENT NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
            DESIGNATION VARCHAR2(150 CHAR) NOT NULL,
            CATEGORIE VARCHAR2(80 CHAR) NOT NULL,
            QUANTITE NUMBER(10) DEFAULT 0 NOT NULL,
            ETAT VARCHAR2(40 CHAR) NOT NULL,
            DATE_PEREMPTION DATE,
            DATE_ACQUISITION DATE,
            DATE_PROCHAIN_CONTROLE DATE,
            IMMATRICULATION VARCHAR2(30 CHAR),
            SEUIL_ALERTE NUMBER(10) DEFAULT 5 NOT NULL,
            CONSTRAINT CK_EQUIPEMENTS_QTE CHECK (QUANTITE >= 0),
            CONSTRAINT CK_EQUIPEMENTS_SEUIL CHECK (SEUIL_ALERTE >= 0)
        )~';
        DBMS_OUTPUT.PUT_LINE('Table EQUIPEMENTS créée selon le MLD et les champs CRUD.');
    ELSE
        -- Vérifie les attributs communs du MLD avant toute modification.
        SELECT COUNT(*) INTO v_count
          FROM USER_TAB_COLUMNS
         WHERE TABLE_NAME = 'EQUIPEMENTS'
           AND COLUMN_NAME IN ('ID_EQUIPEMENT', 'CATEGORIE', 'QUANTITE',
                               'ETAT', 'DATE_PEREMPTION');
        IF v_count <> 5 THEN
            RAISE_APPLICATION_ERROR(-20001,
                'EQUIPEMENTS existe, mais ses colonnes ID_EQUIPEMENT, CATEGORIE, QUANTITE, '
                || 'ETAT et DATE_PEREMPTION ne correspondent pas au MLD attendu. '
                || 'Aucune colonne CRUD n''a été ajoutée. Vérifiez le schéma avec votre équipe.');
        END IF;

        -- DESIGNATION (nom) est absente du schéma actuel. On la laisse nullable
        -- pour préserver les lignes déjà présentes; le formulaire l'exige aux nouveaux ajouts.
        ajouter_colonne('DESIGNATION', 'VARCHAR2(150 CHAR)');
        ajouter_colonne('DATE_ACQUISITION', 'DATE');
        ajouter_colonne('DATE_PROCHAIN_CONTROLE', 'DATE');
        ajouter_colonne('IMMATRICULATION', 'VARCHAR2(30 CHAR)');
        ajouter_colonne('SEUIL_ALERTE', 'NUMBER(10) DEFAULT 5 NOT NULL');
        DBMS_OUTPUT.PUT_LINE('Schéma EQUIPEMENTS complété; les données existantes sont conservées.');
    END IF;

    -- Le formulaire ne demande pas l'ID. Assure sa génération pour les schémas
    -- legacy sans colonne IDENTITY et sans trigger existant qui remplit cet ID.
    SELECT COUNT(*) INTO v_identity
      FROM USER_TAB_IDENTITY_COLS
     WHERE TABLE_NAME = 'EQUIPEMENTS'
       AND COLUMN_NAME = 'ID_EQUIPEMENT';
    SELECT COUNT(DISTINCT t.TRIGGER_NAME) INTO v_id_trigger
      FROM USER_TRIGGERS t
      JOIN USER_SOURCE s ON s.NAME = t.TRIGGER_NAME AND s.TYPE = 'TRIGGER'
     WHERE t.TABLE_NAME = 'EQUIPEMENTS'
       AND t.STATUS = 'ENABLED'
       AND INSTR(UPPER(t.TRIGGERING_EVENT), 'INSERT') > 0
       AND UPPER(s.TEXT) LIKE '%ID_EQUIPEMENT%'
       AND UPPER(s.TEXT) LIKE '%NEW%';
    IF v_identity = 0 AND v_id_trigger = 0 THEN
        SELECT COUNT(*) INTO v_count FROM USER_SEQUENCES
         WHERE SEQUENCE_NAME = 'SEQ_EQUIPEMENTS_CRUD';
        IF v_count = 0 THEN
            SELECT NVL(MAX(ID_EQUIPEMENT), 0) + 1 INTO v_next_id FROM EQUIPEMENTS;
            EXECUTE IMMEDIATE 'CREATE SEQUENCE SEQ_EQUIPEMENTS_CRUD START WITH '
                || TO_CHAR(v_next_id) || ' INCREMENT BY 1 NOCACHE';
        END IF;
        SELECT COUNT(*) INTO v_count FROM USER_TRIGGERS
         WHERE TRIGGER_NAME = 'TRG_EQUIPEMENTS_CRUD_ID';
        IF v_count = 0 THEN
            EXECUTE IMMEDIATE 'CREATE OR REPLACE TRIGGER TRG_EQUIPEMENTS_CRUD_ID '
                || 'BEFORE INSERT ON EQUIPEMENTS FOR EACH ROW '
                || 'WHEN (NEW.ID_EQUIPEMENT IS NULL) '
                || 'BEGIN SELECT SEQ_EQUIPEMENTS_CRUD.NEXTVAL '
                || 'INTO :NEW.ID_EQUIPEMENT FROM DUAL; END;';
        END IF;
        DBMS_OUTPUT.PUT_LINE('Génération de ID_EQUIPEMENT configurée par séquence/trigger.');
    END IF;

    -- Ajoute la clé étrangère seulement si VEHICULES possède déjà une clé
    -- primaire/unique sur IMMATRICULATION et que les valeurs existantes sont valides.
    SELECT COUNT(*) INTO v_count
      FROM USER_CONSTRAINTS c
      JOIN USER_CONS_COLUMNS cc
        ON cc.CONSTRAINT_NAME = c.CONSTRAINT_NAME
       AND cc.TABLE_NAME = c.TABLE_NAME
     WHERE c.TABLE_NAME = 'VEHICULES'
       AND c.CONSTRAINT_TYPE IN ('P', 'U')
       AND cc.COLUMN_NAME = 'IMMATRICULATION';

    IF v_count > 0 THEN
        SELECT COUNT(*) INTO v_count
          FROM USER_CONSTRAINTS child_c
          JOIN USER_CONS_COLUMNS child_cc
            ON child_cc.CONSTRAINT_NAME = child_c.CONSTRAINT_NAME
           AND child_cc.TABLE_NAME = child_c.TABLE_NAME
          JOIN USER_CONSTRAINTS parent_c
            ON parent_c.CONSTRAINT_NAME = child_c.R_CONSTRAINT_NAME
           AND parent_c.TABLE_NAME = 'VEHICULES'
          JOIN USER_CONS_COLUMNS parent_cc
            ON parent_cc.CONSTRAINT_NAME = parent_c.CONSTRAINT_NAME
           AND parent_cc.TABLE_NAME = parent_c.TABLE_NAME
           AND parent_cc.POSITION = child_cc.POSITION
         WHERE child_c.TABLE_NAME = 'EQUIPEMENTS'
           AND child_c.CONSTRAINT_TYPE = 'R'
           AND child_cc.COLUMN_NAME = 'IMMATRICULATION'
           AND parent_cc.COLUMN_NAME = 'IMMATRICULATION';
        IF v_count = 0 THEN
            SELECT COUNT(*) INTO v_count
              FROM EQUIPEMENTS e
             WHERE e.IMMATRICULATION IS NOT NULL
               AND NOT EXISTS (SELECT 1 FROM VEHICULES v
                                WHERE v.IMMATRICULATION = e.IMMATRICULATION);
            IF v_count = 0 THEN
                EXECUTE IMMEDIATE 'ALTER TABLE EQUIPEMENTS ADD CONSTRAINT '
                    || 'FK_EQUIPEMENTS_VEHICULE FOREIGN KEY (IMMATRICULATION) '
                    || 'REFERENCES VEHICULES (IMMATRICULATION)';
                DBMS_OUTPUT.PUT_LINE('Lien MLD EQUIPEMENTS → VEHICULES ajouté.');
            ELSE
                DBMS_OUTPUT.PUT_LINE('Lien véhicule ignoré : des immatriculations existantes sont inconnues dans VEHICULES.');
            END IF;
        ELSE
            DBMS_OUTPUT.PUT_LINE('Lien EQUIPEMENTS → VEHICULES déjà présent; aucune modification nécessaire.');
        END IF;
    ELSE
        DBMS_OUTPUT.PUT_LINE('Table/clé VEHICULES(IMMATRICULATION) absente : le lien sera ajouté quand elle existera.');
    END IF;
END;
/

COMMIT;

-- Vérification après exécution :
SELECT ID_EQUIPEMENT, DESIGNATION, CATEGORIE, QUANTITE, ETAT,
       DATE_PEREMPTION, DATE_ACQUISITION, DATE_PROCHAIN_CONTROLE,
       IMMATRICULATION, SEUIL_ALERTE
  FROM EQUIPEMENTS
 WHERE 1 = 0;

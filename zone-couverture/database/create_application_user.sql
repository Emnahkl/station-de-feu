-- A executer dans SQL Developer avec une connexion SYSTEM.
-- Lancer avec F5 (Run Script). SQL Developer demandera le mot de passe.
ACCEPT app_password CHAR PROMPT 'Mot de passe FIRESTATION_APP : ' HIDE
CREATE USER FIRESTATION_APP IDENTIFIED BY "&app_password"
  DEFAULT TABLESPACE USERS
  TEMPORARY TABLESPACE TEMP
  QUOTA 100M ON USERS;

GRANT CREATE SESSION, CREATE TABLE, CREATE SEQUENCE, CREATE TRIGGER
  TO FIRESTATION_APP;

ALTER USER FIRESTATION_APP ACCOUNT UNLOCK;
UNDEFINE app_password

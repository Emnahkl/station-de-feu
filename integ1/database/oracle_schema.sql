/

CREATE OR REPLACE TRIGGER TRG_CAMPAGNES_ID
BEFORE INSERT ON CAMPAGNES_SENSIBILISATION
FOR EACH ROW
WHEN (NEW.ID_CAMPAGNE IS NULL)
BEGIN
  SELECT SEQ_CAMPAGNES.NEXTVAL INTO :NEW.ID_CAMPAGNE FROM DUAL;
END;
/

CREATE OR REPLACE TRIGGER TRG_INTERVENTIONS_ID
BEFORE INSERT ON INTERVENTIONS
FOR EACH ROW
WHEN (NEW.ID_INTERVENTION IS NULL)
BEGIN
  SELECT SEQ_INTERVENTIONS.NEXTVAL INTO :NEW.ID_INTERVENTION FROM DUAL;
END;
/

CREATE OR REPLACE TRIGGER TRG_VEH_EVENEMENT_BI
BEFORE INSERT ON VEHICULE_EVENEMENTS
FOR EACH ROW
WHEN (NEW.ID_EVENEMENT IS NULL)
BEGIN
  SELECT SEQ_VEHICULE_EVENEMENTS.NEXTVAL INTO :NEW.ID_EVENEMENT FROM DUAL;
END;
/


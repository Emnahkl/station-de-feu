BEFORE INSERT ON EMPLOYES
FOR EACH ROW
WHEN (NEW.ID_EMPLOYE IS NULL)
BEGIN
  SELECT SEQ_EMPLOYES.NEXTVAL INTO :NEW.ID_EMPLOYE FROM DUAL;

-- Use a fresh application schema. This script intentionally does not drop existing objects.
-- ---------------------------------------------------------------------
-- 1. TABLES PRINCIPALES
-- ---------------------------------------------------------------------
CREATE TABLE ZONE_COUVERTURE (
  ID_ZONE            NUMBER PRIMARY KEY,
  NOM                VARCHAR2(50) NOT NULL,
  REGION             VARCHAR2(50),
  SUPERFICIE         NUMBER,
  POPULATION         NUMBER,
  NIVEAU_RISQUE      VARCHAR2(20),
  TEMPS_INTERVENTION NUMBER
);

CREATE TABLE EMPLOYES (
  ID_EMPLOYE    NUMBER PRIMARY KEY,
  NOM_PRENOM    VARCHAR2(100) NOT NULL,
  GRADE         VARCHAR2(50),
  SPECIALITE    VARCHAR2(50),
  TELEPHONE     VARCHAR2(20),
  MOT_DE_PASSE  VARCHAR2(255) NOT NULL
);

CREATE TABLE VEHICULES (
  IMMATRICULATION      VARCHAR2(20) PRIMARY KEY,
  TYPE                 VARCHAR2(50),
  ETAT                 VARCHAR2(30),
  MODELE               VARCHAR2(50),
  KILOMETRAGE          NUMBER(8),
  DERNIERE_MAINTENANCE DATE,
  KM_DERNIERE_MAINTENANCE NUMBER(8)
);

CREATE TABLE VEHICULE_EVENEMENTS (
  ID_EVENEMENT       NUMBER PRIMARY KEY,
  IMMATRICULATION    VARCHAR2(20) NOT NULL,
  TYPE_EVENEMENT     VARCHAR2(40) NOT NULL,
  DATE_EVENEMENT     DATE DEFAULT SYSDATE NOT NULL,
  DETAILS            VARCHAR2(500)
);

-- Association CONTENIR (0,1 côté équipement) -> clé étrangère IMMATRICULATION
CREATE TABLE EQUIPEMENTS (
  ID_EQUIPEMENT    NUMBER PRIMARY KEY,
  CATEGORIE        VARCHAR2(50) NOT NULL,
  QUANTITE         NUMBER(6) DEFAULT 0,
  ETAT             VARCHAR2(30),
  DATE_PEREMPTION  DATE,
  IMMATRICULATION  VARCHAR2(20),
  CONSTRAINT CK_EQUIP_QTE CHECK (QUANTITE >= 0),
  CONSTRAINT FK_EQUIP_VEH FOREIGN KEY (IMMATRICULATION)
    REFERENCES VEHICULES (IMMATRICULATION) ON DELETE SET NULL
);

CREATE TABLE CAMPAGNES_SENSIBILISATION (
  ID_CAMPAGNE          NUMBER PRIMARY KEY,
  TITRE                VARCHAR2(100) NOT NULL,
  THEME                VARCHAR2(100),
  DATE_CAMPAGNE        DATE,
  LIEU                 VARCHAR2(100),
  PUBLIC_CIBLE         VARCHAR2(100),
  NOMBRE_PARTICIPANTS  NUMBER(6),
  CONSTRAINT CK_CAMP_NB CHECK (NOMBRE_PARTICIPANTS >= 0)
);

-- Association SE DEROULER (1,1 côté intervention) -> clé étrangère ID_ZONE
-- GRAVITE et STATUT sont utilisées par l'application Qt (module Interventions).
CREATE TABLE INTERVENTIONS (
  ID_INTERVENTION    NUMBER PRIMARY KEY,
  TYPE_INTERVENTION  VARCHAR2(50)  NOT NULL,
  ADRESSE            VARCHAR2(150) NOT NULL,
  DATE_INTERVENTION  DATE          NOT NULL,
  HEURE              VARCHAR2(5)   NOT NULL,
  GRAVITE            VARCHAR2(20),
  STATUT             VARCHAR2(20),
  ID_ZONE            NUMBER        NOT NULL,
  CONSTRAINT FK_INTER_ZONE FOREIGN KEY (ID_ZONE)
    REFERENCES ZONE_COUVERTURE (ID_ZONE)
);

-- ---------------------------------------------------------------------
-- 2. TABLES ISSUES DES ASSOCIATIONS
-- ---------------------------------------------------------------------
-- Association ternaire PARTICIPER / UTILISER
CREATE TABLE PARTICIPER_UTILISER (
  ID_EMPLOYE       NUMBER       NOT NULL,
  IMMATRICULATION  VARCHAR2(20) NOT NULL,
  ID_INTERVENTION  NUMBER       NOT NULL,
  CONSTRAINT PK_PARTICIPER_UTILISER
    PRIMARY KEY (ID_EMPLOYE, IMMATRICULATION, ID_INTERVENTION),
  CONSTRAINT FK_PU_EMPLOYE FOREIGN KEY (ID_EMPLOYE)
    REFERENCES EMPLOYES (ID_EMPLOYE) ON DELETE CASCADE,
  CONSTRAINT FK_PU_VEHICULE FOREIGN KEY (IMMATRICULATION)
    REFERENCES VEHICULES (IMMATRICULATION) ON DELETE CASCADE,
  CONSTRAINT FK_PU_INTERV FOREIGN KEY (ID_INTERVENTION)
    REFERENCES INTERVENTIONS (ID_INTERVENTION) ON DELETE CASCADE
);

CREATE TABLE NECESSITER (
  ID_EQUIPEMENT    NUMBER NOT NULL,
  ID_INTERVENTION  NUMBER NOT NULL,
  CONSTRAINT PK_NECESSITER PRIMARY KEY (ID_EQUIPEMENT, ID_INTERVENTION),
  CONSTRAINT FK_NEC_EQUIP FOREIGN KEY (ID_EQUIPEMENT)
    REFERENCES EQUIPEMENTS (ID_EQUIPEMENT) ON DELETE CASCADE,
  CONSTRAINT FK_NEC_INTERV FOREIGN KEY (ID_INTERVENTION)
    REFERENCES INTERVENTIONS (ID_INTERVENTION) ON DELETE CASCADE
);

CREATE TABLE ANIMER (
  ID_EMPLOYE   NUMBER NOT NULL,
  ID_CAMPAGNE  NUMBER NOT NULL,
  CONSTRAINT PK_ANIMER PRIMARY KEY (ID_EMPLOYE, ID_CAMPAGNE),
  CONSTRAINT FK_ANIM_EMPLOYE FOREIGN KEY (ID_EMPLOYE)
    REFERENCES EMPLOYES (ID_EMPLOYE) ON DELETE CASCADE,
  CONSTRAINT FK_ANIM_CAMPAGNE FOREIGN KEY (ID_CAMPAGNE)
    REFERENCES CAMPAGNES_SENSIBILISATION (ID_CAMPAGNE) ON DELETE CASCADE
);

-- ---------------------------------------------------------------------
-- 3. SEQUENCES (numérotation automatique, compatible 11g)
-- ---------------------------------------------------------------------
CREATE SEQUENCE SEQ_ZONE          START WITH 5 INCREMENT BY 1 NOCACHE;
CREATE SEQUENCE SEQ_EMPLOYES      START WITH 1 INCREMENT BY 1 NOCACHE;
CREATE SEQUENCE SEQ_EQUIPEMENTS   START WITH 1 INCREMENT BY 1 NOCACHE;
CREATE SEQUENCE SEQ_CAMPAGNES     START WITH 1 INCREMENT BY 1 NOCACHE;
CREATE SEQUENCE SEQ_INTERVENTIONS START WITH 1 INCREMENT BY 1 NOCACHE;
CREATE SEQUENCE SEQ_VEHICULE_EVENEMENTS START WITH 1 INCREMENT BY 1 NOCACHE;

-- ---------------------------------------------------------------------
-- 4. TRIGGERS (remplissent l'identifiant si on ne le donne pas)
-- ---------------------------------------------------------------------
CREATE OR REPLACE TRIGGER TRG_ZONE_ID
BEFORE INSERT ON ZONE_COUVERTURE
FOR EACH ROW
WHEN (NEW.ID_ZONE IS NULL)
BEGIN
  SELECT SEQ_ZONE.NEXTVAL INTO :NEW.ID_ZONE FROM DUAL;
END;
/

